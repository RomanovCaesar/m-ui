  var SKIP_TAGS = { SCRIPT: 1, STYLE: 1, TEXTAREA: 1, PRE: 1, CODE: 1, SVG: 1, OPTION: 1, NOSCRIPT: 1 };
  var SKIP_SELECTOR = '#security-segmented,.mui-select-menu,.release-list';

  var lang = 'zh-CN';

  function muiGetLang() {
    var stored = null;
    try { stored = localStorage.getItem('mui-language'); } catch (e) {}
    var value = stored || document.documentElement.getAttribute('data-default-language') || 'zh-CN';
    return value === 'en' ? 'en' : value === 'zh-CN' ? 'zh-CN' : 'zh-CN';
  }

  function muiT(key, params) {
    var table = DICT[lang] || DICT['zh-CN'];
    var text = table[key];
    if (text === undefined) text = DICT['zh-CN'][key];
    if (text === undefined) text = DICT['en'][key];
    if (text === undefined) return key;
    if (params) {
      text = text.replace(/\{(\w+)\}/g, function (match, name) {
        return params[name] !== undefined ? params[name] : match;
      });
    }
    return text;
  }

  function setAttr(el, attr, key) {
    var value = muiT(key);
    if (attr === 'placeholder') el.setAttribute('placeholder', value);
    else if (attr === 'title') el.setAttribute('title', value);
    else if (attr === 'aria-label') el.setAttribute('aria-label', value);
  }

  function textNodesOf(el) {
    var out = [];
    for (var i = 0; i < el.childNodes.length; i++) {
      var node = el.childNodes[i];
      if (node.nodeType === 3 && node.textContent.trim()) out.push(node);
    }
    return out;
  }

  function muiApply(root) {
    root = root || document;
    lang = muiGetLang();
    document.documentElement.lang = lang === 'zh-CN' ? 'zh-CN' : 'en';

    /* 第一遍：已打标元素 */
    var stamped = root.querySelectorAll ? root.querySelectorAll('[data-i18n],[data-i18n-html],[data-i18n-multi],[data-i18n-placeholder],[data-i18n-title],[data-i18n-aria]') : [];
    for (var i = 0; i < stamped.length; i++) {
      var el = stamped[i];
      /* 显式打标的 OPTION/TEXTAREA 视为有意翻译，只跳过绝不该动的标签 */
      if (el.tagName === 'SCRIPT' || el.tagName === 'STYLE' || el.tagName === 'NOSCRIPT' || el.tagName === 'SVG') continue;
      if (el.hasAttribute('data-i18n')) el.textContent = muiT(el.getAttribute('data-i18n'));
      if (el.hasAttribute('data-i18n-html')) el.innerHTML = muiT(el.getAttribute('data-i18n-html'));
      if (el.hasAttribute('data-i18n-multi')) {
        var keys = el.getAttribute('data-i18n-multi').split(',');
        var nodes = textNodesOf(el);
        for (var k = 0; k < keys.length && k < nodes.length; k++) nodes[k].textContent = muiT(keys[k]);
      }
      if (el.hasAttribute('data-i18n-placeholder')) setAttr(el, 'placeholder', el.getAttribute('data-i18n-placeholder'));
      if (el.hasAttribute('data-i18n-title')) setAttr(el, 'title', el.getAttribute('data-i18n-title'));
      if (el.hasAttribute('data-i18n-aria')) setAttr(el, 'aria-label', el.getAttribute('data-i18n-aria'));
    }

    /* 第二遍：未打标元素按原始文案匹配 */
    var all = root.querySelectorAll ? root.querySelectorAll('*') : [];
    for (var j = 0; j < all.length; j++) {
      var node2 = all[j];
      if (node2.id && SKIP_IDS[node2.id]) continue;
      if (node2.closest && node2.closest(SKIP_SELECTOR)) continue;
      if (node2.hasAttribute('data-i18n') || node2.hasAttribute('data-i18n-html') || node2.hasAttribute('data-i18n-multi')) continue;
      /* placeholder/title/aria 对所有标签都翻：SKIP_TAGS 拦的是"别改这个标签的正文"
         （textarea 里是用户数据、option 是协议关键字），它们的提示属性照翻不误。 */
      var ph = node2.getAttribute && node2.getAttribute('placeholder');
      if (ph && !node2.hasAttribute('data-i18n-placeholder') && SOURCE_PH[ph]) {
        node2.setAttribute('data-i18n-placeholder', SOURCE_PH[ph]);
        setAttr(node2, 'placeholder', SOURCE_PH[ph]);
      }
      var ti = node2.getAttribute && node2.getAttribute('title');
      if (ti && !node2.hasAttribute('data-i18n-title') && SOURCE_TITLE[ti]) {
        node2.setAttribute('data-i18n-title', SOURCE_TITLE[ti]);
        setAttr(node2, 'title', SOURCE_TITLE[ti]);
      }
      var al = node2.getAttribute && node2.getAttribute('aria-label');
      if (al && !node2.hasAttribute('data-i18n-aria') && SOURCE_ARIA[al]) {
        node2.setAttribute('data-i18n-aria', SOURCE_ARIA[al]);
        setAttr(node2, 'aria-label', SOURCE_ARIA[al]);
      }
      var matchedKeys = [], matchedNodes = [];
      /* 正文到此为止：textarea 里是用户输入的内容，option 是协议关键字，都不能动。 */
      if (SKIP_TAGS[node2.tagName]) continue;
      var own = textNodesOf(node2);
      for (var m = 0; m < own.length; m++) {
        var t = own[m].textContent.trim();
        if (SOURCE[t]) { matchedKeys.push(SOURCE[t]); matchedNodes.push(own[m]); }
      }
      if (!matchedKeys.length) continue;
      for (var n = 0; n < matchedNodes.length; n++) matchedNodes[n].textContent = muiT(matchedKeys[n]);
      if (matchedKeys.length === 1 && node2.children.length === 0) {
        node2.setAttribute('data-i18n', matchedKeys[0]);
      } else {
        node2.setAttribute('data-i18n-multi', matchedKeys.join(','));
      }
    }
  }

  function muiSetLang(value) {
    var next = value === 'en' ? 'en' : 'zh-CN';
    try { localStorage.setItem('mui-language', next); } catch (e) {}
    lang = next;
    muiApply(document);
    window.dispatchEvent(new Event('mui-langchange'));
  }

  window.muiT = muiT;
  window.muiApply = muiApply;
  window.muiSetLang = muiSetLang;
  window.muiGetLang = muiGetLang;
  window.muiGetAppliedLang = function () { return lang; };

  function boot() {
    lang = muiGetLang();
    muiApply(document);
    window.dispatchEvent(new Event('mui-langchange'));
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
  else boot();
